Future<void> main() async {
  final directory = Directory('../benchmarks/app-quality');
  await directory.create(recursive: true);
  final cases = <Map<String, Object>>[];
  addPairs(cases, 'grammar', grammarErrors);
  addPairs(cases, 'names', nameErrors);
  addPairs(cases, 'format', formatErrors);
  addControls(cases, 'names', nameControls);
  addControls(cases, 'format', formatControls);
  addControls(cases, 'style', styleControls);
  addControls(cases, 'technical', technicalControls);
  if (cases.length != 140) throw StateError('Ожидаются 140 основных случаев');
  await checkNovelty(cases);
  cases.shuffle(Random(5112026));
  final personal = cases
      .where(personalCase)
      .map(
        (row) => {
          ...row,
          'id': '${row['id']}-personal',
          'profile': 'personal',
          'sourceId': row['id']!,
          'names': glossary,
        },
      )
      .toList();
  if (personal.length != 20) {
    throw StateError('Ожидаются 20 повторов со словарём');
  }
  final all = [...cases, ...personal];
  final content = '${all.map(jsonEncode).join('\n')}\n';
  final file = File(p.join(directory.path, 'cases-v1.jsonl'));
  if (await file.exists() && await file.readAsString() != content) {
    throw StateError(
      'Существующий набор отличается. Не перезаписываем зафиксированные данные.',
    );
  }
  await file.writeAsString(content, flush: true);
  stdout.writeln(
    jsonEncode({
      'primary': cases.length,
      'personal': personal.length,
      'sha256': sha256.convert(utf8.encode(content)).toString(),
    }),
  );
}

void addPairs(List<Map<String, Object>> cases, String group, List<Pair> pairs) {
  for (final (i, (text, expected)) in pairs.indexed) {
    cases.add(row('error-$group-${i + 1}', group, 'error', text, expected));
  }
}

void addControls(
  List<Map<String, Object>> cases,
  String group,
  List<String> texts,
) {
  for (final (i, text) in texts.indexed) {
    cases.add(row('control-$group-${i + 1}', group, 'control', text, text));
  }
}

Map<String, Object> row(
  String id,
  String group,
  String kind,
  String text,
  String expected,
) {
  final protected = glossary.where(text.contains).toSet().toList();
  protected.addAll(
    RegExp(
      r'```[\s\S]*?```|`[^`\n]+`|https?://[^\s)]+|[\w.+-]+@[\w.-]+\.[a-z]+',
    ).allMatches(text).map((match) => match.group(0)!),
  );
  protected.addAll(
    RegExp(r'[A-Z]:\\[^\r\n]+|/home/[^\s]+')
        .allMatches(text)
        .map((match) => match.group(0)!),
  );
  protected.addAll(
    text.characters.where(
      (value) => value.runes.any(
        (rune) => rune >= 0x1f000 || rune >= 0x300 && rune <= 0x36f,
      ),
    ),
  );
  if (RegExp(r'\s+').allMatches(text).map((m) => m.group(0)).join('|') !=
      RegExp(r'\s+').allMatches(expected).map((m) => m.group(0)).join('|')) {
    throw StateError('Неожиданное изменение пробельного оформления: $id');
  }
  for (final value in protected) {
    if (!expected.contains(value)) {
      throw StateError('Эталон меняет защищённое: $id');
    }
  }
  return {
    'id': id,
    'profile': 'empty',
    'group': group,
    'kind': kind,
    'text': text,
    'expected': [expected],
    'names': <String>[],
    'protected': protected,
    'preserveWhitespace': true,
  };
}

bool personalCase(Map<String, Object> row) {
  if (row['group'] != 'names') return false;
  final number = int.parse((row['id']! as String).split('-').last);
  return number >= 11;
}

Future<void> checkNovelty(List<Map<String, Object>> cases) async {
  final previous = <String>{};
  await for (final entry in Directory(
    '../benchmarks',
  ).list(recursive: true, followLinks: false)) {
    if (entry is! File || p.extension(entry.path) != '.jsonl') continue;
    final parts = p.split(entry.path);
    if (parts.contains('results') || parts.contains('app-quality')) continue;
    await for (final line
        in entry
            .openRead()
            .transform(utf8.decoder)
            .transform(const LineSplitter())) {
      final json = jsonDecode(line) as Map<String, dynamic>;
      for (final key in ['text', 'input', 'original']) {
        if (json[key] case final String text) previous.add(normalize(text));
      }
    }
  }
  final unique = <String>{};
  for (final item in cases) {
    final text = normalize(item['text']! as String);
    if (!unique.add(text) || previous.contains(text)) {
      throw StateError('Повтор старого текста: ${item['id']}');
    }
  }
}

String normalize(String text) =>
    text.toLowerCase().replaceAll(RegExp(r'\s+'), ' ').trim();

