def paired_rows(pairs, split):
    rows = []
    for number, (category, text, good, bad, protected) in enumerate(pairs, 1):
        assert text.count(good) == 1 and good != bad
        erroneous = text.replace(good, bad, 1)
        assert erroneous.count(bad) == 1
        for suffix, source, edits in [
            ("correct", text, []), ("error", erroneous, [{"original": bad, "replacement": good}]),
        ]:
            assert all(source.count(part) == text.count(part) > 0 for part in protected)
            rows.append({"id": f"precision-{split}-{number:03}-{suffix}", "pair": number,
                         "split": split, "category": category, "text": source, "edits": edits,
                         "protected": protected})
    return rows


def main():
    old = [json.loads(line) for line in (ROOT / "benchmarks/cases-v1.jsonl").read_text(encoding="utf-8").splitlines()]
    dev = [row for row in old if row["split"] == "dev"] + paired_rows(DEV, "dev")
    test = paired_rows(HOLDOUT, "test")
    previous = set()
    for directory in [ROOT / "benchmarks"]:
        for path in directory.rglob("*.jsonl"):
            if any(part in path.parts for part in ["results", "prompt-precision"]):
                continue
            previous.update(row.get("text") for row in [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()])
    assert len(dev) == len({row["text"] for row in dev}) == 80
    assert len(test) == len({row["text"] for row in test}) == 120
    assert not {row["text"] for row in test}.intersection(previous | {row["text"] for row in dev})
    for name, rows in [("dev-v1.jsonl", dev), ("holdout-v1.jsonl", test)]:
        (HERE / name).write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), encoding="utf-8", newline="\n")
    print("Подготовлены dev80 и новый holdout120, без пересечений test с прежними входами.")


if __name__ == "__main__":
    main()
