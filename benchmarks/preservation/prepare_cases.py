def main():
    records = []
    for index, (category, correct, good, bad, protected) in enumerate(PAIRS, 1):
        if correct.count(good) != 1:
            raise ValueError(f"Неоднозначный эталон {index}: {good}")
        erroneous = correct.replace(good, bad, 1)
        if erroneous.count(bad) != 1:
            raise ValueError(f"Неоднозначная ошибка {index}: {bad}")
        for label, text, edits in [
            ("correct", correct, []),
            ("error", erroneous, [{"original": bad, "replacement": good}]),
        ]:
            if any(not part or text.count(part) != correct.count(part) for part in protected):
                raise ValueError(f"Ошибка затрагивает защищённый фрагмент {index}")
            records.append({
                "id": f"preserve-{index:03}-{label}", "pair": index, "split": "test",
                "category": category, "text": text, "edits": edits, "protected": protected,
            })
    root = Path(__file__).resolve().parents[1]
    previous = {json.loads(line)["text"] for line in (root / "cases-v1.jsonl").read_text(encoding="utf-8").splitlines()}
    texts = [row["text"] for row in records]
    if len(records) != 120 or len(set(texts)) != 120 or set(texts) & previous:
        raise ValueError("Неправильный состав нового набора или пересечение с v1")
    target = Path(__file__).with_name("cases-v1.jsonl")
    target.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in records), encoding="utf-8", newline="\n")
    print(f"Подготовлено {len(records)} текстов, {len(PAIRS)} пар")


if __name__ == "__main__":
    main()
